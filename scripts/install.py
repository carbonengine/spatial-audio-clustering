"""Builds the Spatial Clustering plug-in with CMake against a Wwise SDK and installs it into a
Wwise install and a game, for example ones kept in source control.

    python scripts/install.py --wwise-sdk <SDK folder> --wwise-root <Wwise install>
    python scripts/install.py --wwise-sdk <SDK folder> --runtime <folder>
    python scripts/install.py --wwise-sdk <SDK folder> --wwise-root <Wwise install> --runtime <folder> --perforce

--wwise-root  installs the authoring plug-in and its property help into a Wwise install.
--runtime     installs SpatialClustering.dll for dynamic loading, the Release build in
              <folder>/release/bin and the Profile build in <folder>/profile/bin, with
              LICENSE.txt and NOTICE in <folder>.
--perforce    opens the installed files in a pending changelist, a new one or the one given
              with --changelist: files already in the depot for edit, new files for add, and
              help pages that the new version no longer has for delete. It never submits.

Use the SDK of the same Wwise version as the Wwise install and the game's sound engine. The
property help is generated by `wp.py build Documentation`, run in the wwise folder.
Windows only, with Visual Studio 2026 and the MSVC v143 build tools for the authoring plug-in.
"""

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
BUILD_DIR = REPO_ROOT / "build"
HELP_MD_DIR = REPO_ROOT / "wwise" / "WwisePlugin" / "res" / "Md" / "en"
HELP_HTML_DIR = REPO_ROOT / "wwise" / "WwisePlugin" / "res" / "Html" / "en"
VERSION_HEADER = REPO_ROOT / "wwise" / "SpatialClusteringVersion.h"
GENERATOR = ["-G", "Visual Studio 18 2026", "-A", "x64"]

# Installed help pages live here, relative to the Wwise install.
INSTALLED_HELP_DIR = Path("Authoring/Data/Plugins/SpatialClustering/Html/en")

# (CMake configuration, runtime folder). Only Release defines AK_OPTIMIZED, so RelWithDebInfo
# builds the plug-in for the Profile sound engine.
RUNTIME_BUILDS = [("Release", "release"), ("RelWithDebInfo", "profile")]


def fail(message):
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def run(command, **kwargs):
    print(f"\n> {' '.join(str(part) for part in command)}", flush=True)
    result = subprocess.run([str(part) for part in command], **kwargs)
    if result.returncode != 0:
        fail(f"{Path(str(command[0])).name} failed with exit code {result.returncode}")
    return result


def find_cmake():
    """Returns cmake from PATH, or else the one that comes with Visual Studio."""
    cmake = shutil.which("cmake")
    if cmake:
        return cmake
    vswhere = Path(r"C:\Program Files (x86)\Microsoft Visual Studio\Installer\vswhere.exe")
    if vswhere.exists():
        found = subprocess.run(
            [str(vswhere), "-latest", "-products", "*", "-find",
             r"Common7\IDE\CommonExtensions\Microsoft\CMake\CMake\bin\cmake.exe"],
            capture_output=True, text=True).stdout.strip().splitlines()
        if found:
            return found[0]
    fail("cmake not found. Install it or add it to PATH.")


def read_define(path, pattern, name):
    match = re.search(rf"^#define\s+{name}\s+{pattern}", path.read_text(encoding="utf-8"), re.MULTILINE)
    if not match:
        fail(f"{name} is not defined in {path}")
    return match.group(1)


def sdk_version(sdk_dir):
    header = sdk_dir / "include" / "AK" / "AkWwiseSDKVersion.h"
    if not header.exists():
        fail(f"{sdk_dir} is not a Wwise SDK folder: {header} does not exist")
    parts = ["MAJOR", "MINOR", "SUBMINOR", "BUILD"]
    return ".".join(read_define(header, r"(\d+)", f"AK_WWISESDK_VERSION_{part}") for part in parts)


def check_help_pages():
    """Fails unless there is a generated help page, with the same title, for every Markdown source."""
    sources = {path.stem: path for path in HELP_MD_DIR.glob("*.md")}
    pages = {path.stem: path for path in HELP_HTML_DIR.glob("*.html")} if HELP_HTML_DIR.exists() else {}
    stale = set(sources) ^ set(pages)
    for stem in set(sources) & set(pages):
        title = re.search(r"^#+\s*(.+?)\s*$", sources[stem].read_text(encoding="utf-8"), re.MULTILINE)
        if title and title.group(1) not in pages[stem].read_text(encoding="utf-8"):
            stale.add(stem)
    if stale:
        fail(f"the property help is missing or out of date ({', '.join(sorted(stale))}). Run "
             "`python <Wwise install>/Scripts/Build/Plugins/wp.py build Documentation` in the wwise folder first.")
    return sorted(pages)


def configure_and_build(cmake, build_dir, options, configurations, target):
    run([cmake, "-S", REPO_ROOT, "-B", build_dir, *GENERATOR, *options])
    for configuration in configurations:
        run([cmake, "--build", build_dir, "--config", configuration, "--target", target])


def install(cmake, build_dir, configuration, component, prefix):
    run([cmake, "--install", build_dir, "--config", configuration, "--component", component, "--prefix", prefix])


def existing_folder(path):
    """Returns the nearest folder of path that exists, so p4 finds the workspace's settings."""
    folder = path if path.is_dir() else path.parent
    while not folder.exists():
        folder = folder.parent
    return folder


class Perforce:
    """Opens files in a pending changelist. Every command takes explicit file paths."""

    def __init__(self, changelist, description, workspace_folder):
        if not shutil.which("p4"):
            fail("p4 not found on PATH.")
        self.workspace_folder = workspace_folder
        self.changelist = changelist or self._new_changelist(description)

    def _p4(self, *args, input_text=None, cwd=None):
        return subprocess.run(["p4", *args], input=input_text, capture_output=True, text=True,
                              cwd=cwd or self.workspace_folder)

    def _new_changelist(self, description):
        spec = self._p4("--field", f"Description={description}", "--field", "Files=", "change", "-o").stdout
        result = self._p4("change", "-i", input_text=spec)
        match = re.search(r"Change (\d+) created", result.stdout)
        if not match:
            fail(f"could not create a changelist: {result.stdout}{result.stderr}")
        return match.group(1)

    def depot_state(self, files):
        """Returns {file: 'tracked' | 'opened' | 'new'} for local file paths."""
        state = {}
        for path in files:
            fields = self._p4("fstat", "-T", "headAction,action", str(path), cwd=existing_folder(path)).stdout
            if re.search(r"^\.\.\. action ", fields, re.MULTILINE):
                state[path] = "opened"
            elif re.search(r"^\.\.\. headAction (?!delete|move/delete)", fields, re.MULTILINE):
                state[path] = "tracked"
            else:
                state[path] = "new"
        return state

    def open(self, command, files):
        for path in files:
            result = self._p4(command, "-c", self.changelist, str(path), cwd=existing_folder(path))
            print(f"  {(result.stdout or result.stderr).strip()}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--wwise-sdk", type=Path, required=True, help="SDK folder of the Wwise version to build against")
    parser.add_argument("--wwise-root", type=Path, help="Wwise install to install the authoring plug-in into")
    parser.add_argument("--runtime", type=Path, help="folder to install the runtime plug-in DLL into")
    parser.add_argument("--perforce", action="store_true", help="open the installed files in a pending changelist")
    parser.add_argument("--changelist", help="pending changelist to use with --perforce instead of a new one")
    args = parser.parse_args()

    if not args.wwise_root and not args.runtime:
        fail("give --wwise-root, --runtime or both")
    if sys.platform != "win32":
        fail("this script runs on Windows only")

    sdk_dir = args.wwise_sdk.resolve()
    version = read_define(VERSION_HEADER, r'"([^"]+)"', "SPATIALCLUSTERING_VERSION_STRING")
    print(f"Spatial Clustering {version}, built against the Wwise {sdk_version(sdk_dir)} SDK")
    cmake = find_cmake()
    help_pages = check_help_pages() if args.wwise_root else []

    # Work out every installed file first, so files already in Perforce can be opened for edit
    # before the install overwrites them.
    targets = []
    if args.wwise_root:
        wwise_root = args.wwise_root.resolve()
        plugins = wwise_root / "Authoring" / "x64" / "Release" / "bin" / "Plugins"
        targets += [plugins / f"SpatialClustering.{extension}" for extension in ("dll", "pdb", "xml")]
        targets += [wwise_root / INSTALLED_HELP_DIR / f"{page}.html" for page in help_pages]
    if args.runtime:
        runtime = args.runtime.resolve()
        for _, folder in RUNTIME_BUILDS:
            targets += [runtime / folder / "bin" / f"SpatialClustering.{extension}" for extension in ("dll", "pdb")]
        targets += [runtime / "LICENSE.txt", runtime / "NOTICE"]

    if args.wwise_root:
        configure_and_build(cmake, BUILD_DIR / "install-authoring",
                            ["-T", "v143", "-DSPATIALCLUSTERING_BUILD_AUTHORING=ON", f"-DWWISE_SDK_DIR={sdk_dir}"],
                            ["Release"], "SpatialClusteringAuthoring")
    if args.runtime:
        configure_and_build(cmake, BUILD_DIR / "install-runtime",
                            ["-DSPATIALCLUSTERING_BUILD_SHARED=ON", f"-DWWISE_SDK_DIR={sdk_dir}"],
                            [configuration for configuration, _ in RUNTIME_BUILDS], "SpatialClusteringShared")

    # Help pages of parameters that the new version no longer has.
    old_pages = []
    if args.wwise_root:
        installed_help = wwise_root / INSTALLED_HELP_DIR
        if installed_help.exists():
            old_pages = [path for path in installed_help.glob("*.html") if path.stem not in help_pages]

    p4 = None
    state = {}
    if args.perforce:
        p4 = Perforce(args.changelist, f"Spatial Clustering {version}", existing_folder(targets[0]))
        state = p4.depot_state(targets)
        old_state = p4.depot_state(old_pages)
        print(f"\nOpening files in changelist {p4.changelist}")
        p4.open("edit", [path for path in targets if state[path] == "tracked"])
        p4.open("delete", [path for path in old_pages if old_state[path] == "tracked"])
    for path in old_pages:
        if path.exists() and not (p4 and old_state[path] == "opened"):
            path.unlink()

    if args.wwise_root:
        install(cmake, BUILD_DIR / "install-authoring", "Release", "Authoring", wwise_root)
    if args.runtime:
        for configuration, folder in RUNTIME_BUILDS:
            install(cmake, BUILD_DIR / "install-runtime", configuration, "SharedRuntime", runtime / folder)
        for name in ("LICENSE.txt", "NOTICE"):
            shutil.copyfile(REPO_ROOT / name, runtime / name)

    if p4:
        p4.open("add", [path for path in targets if state[path] == "new"])
        opened_elsewhere = [path for path in targets if state[path] == "opened"]
        if opened_elsewhere:
            print("\nAlready open, left in their current changelist:")
            for path in opened_elsewhere:
                print(f"  {path}")
        print(f"\nDone. Review changelist {p4.changelist} and submit it yourself.")
    else:
        print("\nDone.")


if __name__ == "__main__":
    main()
